/**
 * Development photography from Unsplash. Regions (percent of the original
 * image) mark where tagged people are. In production these would come from
 * the uploader tagging people plus body detection; here they are hand-placed.
 */

interface PhotoDef {
  id: string;
  ref: string;
  width: number;
  height: number;
  tone: string;
  photographer: string;
  alt: string;
  nodeId: string;
  credit?: string;
  focal?: { x: number; y: number };
  caption?: Photo["caption"];
  people?: PhotoPerson[];
}

const photo = (p: PhotoDef): Photo => ({
  id: p.id,
  src: `https://images.unsplash.com/${p.ref}`,
  width: p.width,
  height: p.height,
  focal: p.focal ?? { x: 50, y: 50 },
  tone: p.tone,
  alt: p.alt,
  caption: p.caption,
  credit: p.credit,
  nodeId: p.nodeId,
  people: p.people ?? [],
  redactions: [],
  source: { provider: "unsplash", photographer: p.photographer },
});

